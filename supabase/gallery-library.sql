-- Expandable public gallery and school-section gallery pages.
-- Safe to run more than once after supabase/media-library.sql.

create table if not exists public.gallery_items (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  section text not null check (
    section in (
      'eyfs',
      'junior-school',
      'senior-school',
      'igcse',
      'a-level',
      'sports-and-co-curricular',
      'whole-school'
    )
  ),
  title text not null,
  caption text,
  image_url text not null,
  image_alt text not null,
  published boolean not null default true,
  sort_order integer not null default 100 check (sort_order >= 0),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists gallery_items_public_section_order_idx
  on public.gallery_items (section, published, sort_order, created_at desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists gallery_items_set_updated_at on public.gallery_items;
create trigger gallery_items_set_updated_at
before update on public.gallery_items
for each row execute function public.set_updated_at();

alter table public.gallery_items enable row level security;

drop policy if exists "published gallery items are public" on public.gallery_items;
create policy "published gallery items are public"
on public.gallery_items for select
to anon, authenticated
using (published = true);

drop policy if exists "admins can read every gallery item" on public.gallery_items;
create policy "admins can read every gallery item"
on public.gallery_items for select
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admins can create gallery items" on public.gallery_items;
create policy "admins can create gallery items"
on public.gallery_items for insert
to authenticated
with check (
  ((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin'
  and created_by = (select auth.uid())
);

drop policy if exists "admins can update gallery items" on public.gallery_items;
create policy "admins can update gallery items"
on public.gallery_items for update
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin')
with check (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admins can delete gallery items" on public.gallery_items;
create policy "admins can delete gallery items"
on public.gallery_items for delete
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

revoke all on table public.gallery_items from anon, authenticated;
grant select on table public.gallery_items to anon, authenticated;
grant insert, update, delete on table public.gallery_items to authenticated;
grant usage, select on sequence public.gallery_items_id_seq to authenticated;

